<?php
require_once __DIR__ . '/../config.php';
$user = requireAuth();
$db = getDB();

$attemptId = (int) ($_GET['attempt_id'] ?? 0);

// Ownership-scoped fetch via explicit REST filters. (The SQL emulator's WHERE parser
// silently drops `a.id = <int>` / `a.student_id = <int>` conditions, which would defeat
// the ownership check entirely — so we query PostgREST directly.)
$attemptRows = supabaseRest('attempts?id=eq.' . $attemptId . '&student_id=eq.' . $user['id'] . '&status=eq.completed&select=*&limit=1');
$attempt = $attemptRows[0] ?? null;
if (!$attempt) { http_response_code(404); exit('Not found'); }

// Test title/mode
$attempt['title'] = 'Practice Test';
$attempt['mode'] = '';
if (!empty($attempt['test_id'])) {
    $testRows = supabaseRest('tests?id=eq.' . $attempt['test_id'] . '&select=title,mode&limit=1');
    if (!empty($testRows[0])) {
        $attempt['title'] = $testRows[0]['title'] ?? 'Practice Test';
        $attempt['mode'] = $testRows[0]['mode'] ?? '';
    }
}

// Answers + question enrichment (subject/difficulty/position)
$allAnswers = supabaseRest('attempt_answers?attempt_id=eq.' . $attemptId . '&select=*') ?? [];
$qIds = array_filter(array_column($allAnswers, 'question_id'));
$qMap = [];
if ($qIds) {
    $qRows = supabaseRest('questions?id=in.(' . implode(',', $qIds) . ')&select=id,question_text,subject,difficulty,position') ?? [];
    foreach ($qRows as $q) $qMap[$q['id']] = $q;
}
foreach ($allAnswers as &$a) {
    $q = $qMap[$a['question_id']] ?? [];
    $a['question_text'] = $q['question_text'] ?? '';
    $a['subject'] = $q['subject'] ?? '';
    $a['difficulty'] = $q['difficulty'] ?? '';
    $a['position'] = $q['position'] ?? 0;
}
unset($a);
usort($allAnswers, fn($x, $y) => ($x['position'] ?? 0) <=> ($y['position'] ?? 0));

// Generate HTML-based printable report (can be printed to PDF via browser)
header('Content-Type: text/html');
?>
<!DOCTYPE html>
<html>
<head>
<title>Report - <?= htmlspecialchars($attempt['title']) ?></title>
<style>
    body { font-family: Arial, sans-serif; font-size: 12px; padding: 40px; color: #333; }
    h1 { font-size: 20px; margin-bottom: 4px; }
    .subtitle { color: #666; margin-bottom: 24px; }
    table { width: 100%; border-collapse: collapse; margin-bottom: 24px; }
    th, td { border: 1px solid #ddd; padding: 8px; text-align: left; }
    th { background: #f5f5f5; }
    .score-box { display: inline-block; padding: 8px 16px; background: #e8f5e9; border-radius: 6px; font-size: 18px; font-weight: bold; margin-bottom: 16px; }
    @media print { body { padding: 20px; } }
</style>
</head>
<body>
<h1>DDCET Prep — Test Report Card</h1>
<p class="subtitle"><?= htmlspecialchars($attempt['title']) ?> | <?= htmlspecialchars($user['name']) ?> | <?= date('d M Y', strtotime($attempt['completed_at'])) ?></p>

<div class="score-box"><?= $attempt['score'] ?> / <?= $attempt['total_marks'] ?> (<?= $attempt['total_marks'] > 0 ? round($attempt['score']/$attempt['total_marks']*100) : 0 ?>%)</div>

<table>
<tr><th>Metric</th><th>Value</th></tr>
<tr><td>Correct</td><td><?= $attempt['correct_count'] ?></td></tr>
<tr><td>Incorrect</td><td><?= $attempt['incorrect_count'] ?></td></tr>
<tr><td>Skipped</td><td><?= $attempt['skipped_count'] ?></td></tr>
<tr><td>Time Spent</td><td><?= floor($attempt['time_spent_seconds']/60) ?>m <?= $attempt['time_spent_seconds']%60 ?>s</td></tr>
<tr><td>Percentile</td><td><?= $attempt['percentile'] ?>%</td></tr>
</table>

<h2>Question-wise Summary</h2>
<table>
<tr><th>#</th><th>Subject</th><th>Difficulty</th><th>Result</th><th>Time</th></tr>
<?php foreach ($allAnswers as $i => $a): ?>
<tr>
    <td><?= $i+1 ?></td>
    <td><?= htmlspecialchars($a['subject']) ?></td>
    <td><?= $a['difficulty'] ?></td>
    <td><?= $a['is_correct'] === true ? 'Correct' : ($a['is_correct'] === false ? 'Wrong' : 'Skipped') ?></td>
    <td><?= $a['time_spent_seconds'] ?>s</td>
</tr>
<?php endforeach; ?>
</table>

<p style="text-align: center; color: #888; margin-top: 40px;">Generated by DDCET Prep Platform • <?= date('d M Y, h:i A') ?></p>
<script>window.print();</script>
</body>
</html>
